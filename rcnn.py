# Corresponding labels and ground truth bounding boxes (manually given for demo)
labels = ["car", "bike", "bus"]
gt_boxes = [  # (x, y, w, h)
    (50, 50, 200, 150),  # car box
    (30, 30, 120, 100),  # bike box
    (70, 70, 220, 160)   # bus box
]

base_model = VGG16(weights='imagenet')
feature_extractor = Model(inputs=base_model.input, outputs=base_model.get_layer('fc1').output)

def get_region_proposals(img):
    ss = cv2.ximgproc.segmentation.createSelectiveSearchSegmentation()
    ss.setBaseImage(img)
    ss.switchToSelectiveSearchFast()
    rects = ss.process()
    return rects[:100]  # limit to 100 regions
def extract_features(image, box):
    x, y, w, h = box
    roi = image[y:y+h, x:x+w]
    roi = cv2.resize(roi, (224, 224))
    roi = np.expand_dims(roi, axis=0)
    roi = preprocess_input(roi)
    features = feature_extractor.predict(roi)
    return features.flatten()

X_train = []
y_train = []

for idx, path in enumerate(image_paths):
    img = cv2.imread(path)
    boxes = get_region_proposals(img)
    gt = gt_boxes[idx]

    for box in boxes:
        x, y, w, h = box
        iou = calculate_iou(gt, (x, y, w, h))
        if iou > 0.5:
            feat = extract_features(img, box)
            X_train.append(feat)
            y_train.append(labels[idx])

def calculate_iou(box1, box2):
    x1, y1, w1, h1 = box1
    x2, y2, w2, h2 = box2

    xi1 = max(x1, x2)
    yi1 = max(y1, y2)
    xi2 = min(x1+w1, x2+w2)
    yi2 = min(y1+h1, y2+h2)

    inter_area = max(0, xi2 - xi1) * max(0, yi2 - yi1)
    box1_area = w1 * h1
    box2_area = w2 * h2
    union = box1_area + box2_area - inter_area

    return inter_area / union

le = LabelEncoder()
y_encoded = le.fit_transform(y_train)

svm = SVC(probability=True)
svm.fit(X_train, y_encoded)

test_image = cv2.imread("/content/sample_data/car.png")
test_boxes = get_region_proposals(test_image)

for box in test_boxes:
    x, y, w, h = box
