import cv2
import numpy as np
from sklearn.svm import SVC
from sklearn.linear_model import LinearRegression
from tensorflow.keras.applications.vgg16 import VGG16, preprocess_input
from tensorflow.keras.models import Model
from tensorflow.keras.preprocessing.image import img_to_array
from google.colab.patches import cv2_imshow

# --------------------------
# Load pre-trained CNN (VGG16) for feature extraction (excluding classifier layers)
base_model = VGG16(weights='imagenet', include_top=True)
feature_extractor = Model(inputs=base_model.input, outputs=base_model.get_layer("fc1").output)

# --------------------------
# 1. Selective Search: Region Proposals
# --------------------------
def get_region_proposals(image):
    ss = cv2.ximgproc.segmentation.createSelectiveSearchSegmentation()
    ss.setBaseImage(image)
    ss.switchToSelectiveSearchFast()
    rects = ss.process()
    return rects[:2000]  # Top 2000 proposals

# --------------------------
# 2. Feature Extraction from CNN
# --------------------------
def extract_features(image, box):
    x, y, w, h = box
    roi = image[y:y+h, x:x+w]
    roi = cv2.resize(roi, (224, 224))
    roi = img_to_array(roi)
    roi = np.expand_dims(roi, axis=0)
    roi = preprocess_input(roi)
    features = feature_extractor.predict(roi)
    return features[0]

# --------------------------
# 3. Training Example
# --------------------------
X_train = np.random.rand(10, 4096)
y_train = ['car', 'car', 'bus', 'car', 'bike', 'car', 'bus', 'bike', 'car', 'bus']
svm = SVC(probability=True)
bbox_train = []  # Bounding box regression targets

# Sample image and annotations
image = cv2.imread("/content/sample_data/car.png")
gt_boxes = [(50, 30, 150, 150)]  # format: x, y, w, h
gt_labels = ["car"]

proposals = get_region_proposals(image)

for box in proposals:
    x, y, w, h = box
    for i, gt in enumerate(gt_boxes):
        gx, gy, gw, gh = gt

        # Calculate IoU (for training positive samples)
        ix = max(x, gx)
        iy = max(y, gy)
        ax = min(x+w, gx+gw)
        ay = min(y+h, gy+gh)
        inter_area = max(0, ax - ix) * max(0, ay - iy)
        union_area = w*h + gw*gh - inter_area
        iou = inter_area / union_area

        if iou > 0.5:  # Positive match
            feature = extract_features(image, box)
            X_train.append(feature)
            y_train.append(gt_labels[i])

            # Bounding box regression targets: dx, dy, dw, dh
            dx = (gx + gw/2 - (x + w/2)) / w
            dy = (gy + gh/2 - (y + h/2)) / h
            dw = np.log(gw / w)
            dh = np.log(gh / h)
            bbox_train.append([dx, dy, dw, dh])

# --------------------------
# 4. Train SVM & BBox Regressor
# --------------------------
svm = SVC(probability=True)
svm.fit(X_train, y_train)

regressor = LinearRegression()
regressor.fit(X_train, bbox_train)

# --------------------------
# 5. Inference
# --------------------------
test_img = cv2.imread("/content/sample_data/car.png")
proposals = get_region_proposals(test_img)

for box in proposals:
    feature = extract_features(test_img, box)
    pred_label = svm.predict([feature])[0]
    prob = svm.predict_proba([feature]).max()

    if prob > 0.8:
        dx, dy, dw, dh = regressor.predict([feature])[0]
        x, y, w, h = box
        cx, cy = x + w / 2, y + h / 2

        # Apply regression to adjust bbox
        cx += dx * w
        cy += dy * h
        w *= np.exp(dw)
        h *= np.exp(dh)
        x = int(cx - w/2)
        y = int(cy - h/2)

        cv2.rectangle(test_img, (x, y), (x + int(w), y + int(h)), (0, 255, 0), 2)
        cv2.putText(test_img, pred_label, (x, y-10), cv2.FONT_HERSHEY_SIMPLEX, 0.6, (255, 0, 0), 2)

cv2_imshow(test_img)

